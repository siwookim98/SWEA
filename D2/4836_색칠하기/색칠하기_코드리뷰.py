import sys

sys.stdin = open("sample_input.txt")
# 전체 테스트케이스 개수
T = int(input())

# 테스트케이스를 1번부터 T번까지 처리
for tc in range(1, T+1):

    # [TC당 하나] 10x10 격자를 새로 만든다
    # 앞 테스트케이스의 색칠 흔적이 남으면 안 되므로 매번 초기화
    # [[0]*10 for _ in range(10)] 형태로 만드는 이유:
    #   [[0]*10]*10 은 같은 리스트 10개를 참조해서 한 행을 바꾸면 전부 바뀜
    empty_arr = [[0] * 10 for _ in range(10)]

    # 이번 테스트케이스에서 칠할 사각형의 개수
    N = int(input())

    # [TC당 하나] 보라색 칸의 개수를 담을 변수
    # empty_arr와 같은 위치에서 초기화 → 격자를 비우는 시점과 세는 통을 비우는 시점이 일치
    # N 루프 안에 두면 사각형마다 리셋되어 마지막 사각형 결과만 남음 (대표적인 오답 원인)
    # count = 0

    # 사각형을 하나씩 읽어서 칠한다
    for i in range(N):

        count = 0
        # [사각형당 하나] 왼쪽 위 (r1, c1) ~ 오른쪽 아래 (r2, c2), 색은 1(빨강) 또는 2(파랑)
        r1, c1, r2, c2, color = map(int, input().split())

        # r1행 ~ r2행까지, 각 행의 c1열 ~ c2열까지 칠한다 (행 우선 순회)
        # range는 끝 값을 포함하지 않으므로 r2, c2에 +1 필수
        for r in range(r1, r2+1):      # 바깥: 행 이동

            for c in range(c1, c2+1):  # 안쪽: 그 행의 열 이동

                # 칠해진 색 값을 더한다
                # 빨강(1) + 파랑(2) = 3 이 보라색을 뜻함
                empty_arr[r][c] += color

                # 방금 더해서 3이 된 칸이 곧 새로 생긴 보라색 칸
                # 값이 계속 커지기만 하므로 한 칸이 3을 거치는 순간은 최대 한 번 → 중복 카운트 없음
                if empty_arr[r][c] == 3:

                    count += 1

    # [TC당 한 번] 이번 테스트케이스의 답을 출력
    # print가 N 루프 안에 있으면 사각형 개수만큼 출력되므로 위치 주의
    print(f'#{tc} {count}')

    # count 변수는 테스트케이스 하나당 보라색 칸 수 이다.
    # 그러니 테스트케이스가 시작될 때마다 초기화한다.  
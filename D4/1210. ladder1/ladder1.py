import sys

sys.stdin = open('input.txt')

for tc in range(1, 11):
    N = int(input())  # 리뷰: N을 읽지만 이후 로직에서 전혀 사용하지 않음 (100x100 고정 크기라 상관은 없으나, 왜 필요한 입력인지 주석으로 남겨두면 좋음)
    matrix = [list(map(int, input().split())) for _ in range(100)]  # 원본 격자 저장

    dr = [0, 0, 1]  # 행(row)의 변화량 : 좌, 우, 하
    dc = [-1, 1, 0]  # 열(column)의 변화량 : 좌, 우, 하
    # 리뷰: 좌→우→하 순서가 "가로줄을 만나면 무조건 꺾는다"는 사다리 타기 규칙 구현의 핵심.
    # 이 순서를 바꾸면 오답이 나오므로, 이 부분에 규칙 설명 주석을 남겨두는 게 좋음.

    answer = 0
    # 리뷰(중요): 초기값이 0인 게 위험할 수 있음.
    # 만약 어떤 테스트케이스에서 "정답을 못 찾는" 경우가 생긴다면(이론상 문제 조건상 없어야 하지만),
    # answer=0은 "0번 열이 정답"이라는 값과 구분이 안 됨.
    # 못 찾았을 때를 명확히 구분하려면 answer = -1로 초기화하는 게 더 안전한 관례.
    # (이 문제는 항상 정답이 존재한다는 보장이 있다면 실제 동작엔 문제 없음 — 다만 방어적 코딩 관점에서 짚음)

    for start_column in range(100):
        # 맨 윗줄(0행)에서 길이 시작되는(값이 1인) 열만 출발점 후보로 검사
        if matrix[0][start_column] == 1:

            test_map = [row[:] for row in matrix]
            # 리뷰: 매 출발점마다 100x100 리스트를 통째로 복사(deepcopy 수준의 얕은 복사 반복).
            # 정답을 찾으면 break로 빠져나가긴 하지만, 최악의 경우 최대 100번 복사가 일어남.
            # 성능상 큰 문제는 없는 크기(100x100)라 실용적으로는 괜찮음.
            # 다만 매번 새로 복사하는 대신, 지나간 경로만 따로 기록(방문 집합)하고
            # 루프가 끝난 뒤 원상복구하는 방식도 대안이 될 수 있음.

            r, c = 0, start_column  # 현재 위치 초기화

            while r < 99:  # 맨 아랫줄(99행) 도달 전까지 반복
                for i in range(3):
                    nr = r + dr[i]
                    nc = c + dc[i]

                    # 격자 범위 안이고, 이동할 값이 1 이상(길 또는 목적지)인 경우 이동
                    if 0 <= nr < 100 and 0 <= nc < 100 and test_map[nr][nc] >= 1:
                        test_map[r][c] = 0
                        # 리뷰: 지나온 칸을 0으로 지워서 "왔던 길로 되돌아가는 것"을 방지.
                        # 이 한 줄이 없으면 좌/우로 이동한 뒤 바로 원래 자리로 되돌아가는
                        # 무한 루프 혹은 오작동이 생길 수 있음 — 핵심 안전장치.
                        r, c = nr, nc
                        break
                        # 리뷰: for-break 구조라서 "이동 방향을 못 찾는 경우"에 대한 처리가 없음.
                        # 문제 조건상 항상 아래로 갈 길이 있다고 보장되면 괜찮지만,
                        # 그렇지 않다면 여기서 무한 루프에 빠질 위험이 있음 (r이 갱신되지 않는 채 while이 계속 돎).
                        # 방어적으로 "이동 실패 시 탈출" 로직을 추가하면 더 안전함.

            # while 루프 종료 후, 도착한 좌표의 '원본' 값이 2(목적지)인지 확인
            if matrix[r][c] == 2:
                answer = start_column
                break  # 정답을 찾았으므로 나머지 출발점은 검사할 필요 없음 (조기 종료 최적화)

    print(f'#{tc} {answer}')